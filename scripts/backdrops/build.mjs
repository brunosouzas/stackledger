// Maintainer only, offline (metro-map: Backdrop data generation). Not published. Reads only the committed
// london-extract.json (see refresh.mjs), simplifies it with mapshaper (2%, keep-shapes), drops slivers under
// 2 ha, rounds to whole metres, winds every outer ring counter-clockwise and every hole clockwise (y up), so
// the default non-zero fill rule leaves holes empty, and writes src/map/backdrops/london.ts. The tool version
// is pinned; running the script twice gives the same module byte for byte.
// Usage: node scripts/backdrops/build.mjs [out.ts]  (default src/map/backdrops/london.ts; the test writes elsewhere)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAPSHAPER = 'mapshaper@0.7.98';
const here = dirname(fileURLToPath(import.meta.url));
const target = process.argv[2] ? resolve(process.argv[2]) : join(here, '../../src/map/backdrops/london.ts');
const source = JSON.parse(readFileSync(join(here, 'london-extract.json'), 'utf8'));
const work = mkdtempSync(join(tmpdir(), 'stackledger-backdrop-'));
let simplified;
try {
  execFileSync('npx', ['--yes', MAPSHAPER, join(here, 'london-extract.json'),
    '-simplify', '2%', 'keep-shapes',
    '-filter-slivers', 'min-area=20000',
    '-o', join(work, 'out.json'), 'format=geojson', 'precision=1'], { stdio: ['ignore', 'ignore', 'inherit'] });
  simplified = JSON.parse(readFileSync(join(work, 'out.json'), 'utf8'));
} finally {
  rmSync(work, { recursive: true, force: true });
}

/** Twice the signed area of a ring, y up: positive when counter-clockwise. */
const area = ring => ring.reduce((sum, [x, y], i) => { const [nx, ny] = ring[(i + 1) % ring.length]; return sum + x * ny - nx * y; }, 0);
const open = ring => {
  const points = ring.map(([x, y]) => [Math.round(x), Math.round(y)]).filter((p, i, all) => i === 0 || p[0] !== all[i - 1][0] || p[1] !== all[i - 1][1]);
  const [first, last] = [points[0], points.at(-1)];
  return first[0] === last[0] && first[1] === last[1] ? points.slice(0, -1) : points;
};
const wound = (ring, outer) => ((area(ring) > 0) === outer ? ring : [...ring].reverse());

const kinds = {};
let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity];
for (const kind of ['water', 'park']) {
  const feature = simplified.features.find(item => item.properties.kind === kind);
  if (!feature) throw new Error(`No ${kind} in the extract`);
  const polygons = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  kinds[kind] = polygons.flatMap(polygon => polygon.map(open).filter(ring => ring.length >= 3).map((ring, i) => wound(ring, i === 0)))
    .map(ring => { for (const [x, y] of ring) { minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y); } return ring.flat(); });
}
const rings = list => list.map(ring => `  [${ring.join(',')}],`).join('\n');
const vertices = Object.values(kinds).flat().reduce((sum, ring) => sum + ring.length / 2, 0);
const module = `// Generated by scripts/backdrops/build.mjs from scripts/backdrops/london-extract.json; do not edit.
// Map data © OpenStreetMap contributors, extract date ${source.extractDate}, available under the
// Open Database License (ODbL) 1.0: https://opendatacommons.org/licenses/odbl/. https://www.openstreetmap.org/copyright
// Central London (bbox 51.455,-0.26 to 51.56,0.06): water and parks, transverse Mercator in whole metres
// centred on 51.5 N, 0.1 W, y up. Each ring is flat [x0, y0, x1, y1, ...], open (the path closes it); outer
// rings run counter-clockwise and holes clockwise. ${vertices} vertices.
export const extractDate = '${source.extractDate}';

// After the first statement, so the compiler keeps the header comment when it drops this type-only import.
import type { Backdrop } from './types.js';

const water: number[][] = [
${rings(kinds.water)}
];

const park: number[][] = [
${rings(kinds.park)}
];

export const london: Backdrop = { name: 'london', extractDate, box: { x: ${minX}, y: ${minY}, w: ${maxX - minX}, h: ${maxY - minY} }, water, park };
`;
writeFileSync(target, module);
console.log(`${target}: ${Buffer.byteLength(module)} bytes, ${vertices} vertices`);
