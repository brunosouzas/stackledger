/** The Markdown pages and Mermaid diagrams of `stackledger skills map` (skills-map-command spec: Page
 * file names, Item page, One-hop diagram, Stable node IDs, Diagram budget, Map index, Text from the
 * files, Mermaid labels, Source files, Deterministic map). Used by src/skills/map-command.ts.
 *
 * Pure: renderMap takes the graph (src/skills/graph.ts), the counts and the real paths the command
 * computed, and returns each page's path inside the map folder and its text. No I/O, no date, no
 * version, so the same files give the same bytes on every machine.
 *
 * Why the text is handled this way: names, descriptions, rule IDs and folder names come from files a
 * fork's pull request can change, and Git hosts render the pages.
 * - Page file names are lowercase ASCII (a valid Agent Skills name, or `_` and hexadecimal UTF-8), so
 *   no name can climb out of the map folder, clash on a case-insensitive file system or be refused by
 *   Windows.
 * - Node IDs are derived from the file name (`s_writer`), never numbered, so adding one item changes
 *   only its own lines in a diff, and no ID can be a Mermaid keyword such as `end`.
 * - Mermaid labels write every character outside a small safe set as a `#<code>;` entity, which
 *   Mermaid shows as text: a label cannot close its node or start a `click` line.
 * - Markdown text is made one line, loses control and format characters (Unicode Cc and Cf: zero-width,
 *   bidirectional and tag characters), and has its special characters escaped, so a description cannot
 *   open a fence, inject HTML, start a list, become a link (GitHub links bare `https://` and `www.`
 *   text) or render math (GitHub renders `$…$`; `\$` is not reliable there, `<span>$</span>` is).
 *   Mermaid labels are cleaned the same way before their own escaping.
 * - Two items of one kind with the same page file name (a hash collision, or names that are not valid
 *   Unicode and encode alike) stop the command before anything is written: one page cannot hold both.
 * - Links point only at pages this module names or at source paths it computes and percent-encodes.
 */
import { createHash } from 'node:crypto';
import { isAbsolute, relative, sep } from 'node:path';
import { InternalError } from '../errors.js';
import type { SkillsSummary, SourceFile } from './source.js';
import { compareListed, incoming, outgoing, reachedThrough, type MapEdge, type MapNode, type NodeKind, type SkillGraph } from './graph.js';

/** The folder of each kind's pages inside the map folder. */
export const KIND_FOLDERS: Record<NodeKind, string> = { skill: 'skills', playbook: 'playbooks', agent: 'agents' };
export const INDEX_PAGE = 'README.md';
/** Labels show at most this many code points of a name (one non-ASCII character can become eight as an entity). */
const MAX_LABEL_CODE_POINTS = 64;
const MAX_DESCRIPTION_CODE_POINTS = 1024;
/** Mermaid 11 refuses more than 500 edges and about 50,000 characters by default; the budget leaves room for host differences. */
export const MAX_DIAGRAM_EDGES = 400;
export const MAX_DIAGRAM_CHARACTERS = 40_000;
const MAX_FILE_NAME = 64;
const HASHED_PREFIX = 52;
const HASH_DIGITS = 11;
const VALID_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const WINDOWS_DEVICE = /^(con|prn|aux|nul|com[0-9]|lpt[0-9])$/;
const ID_PREFIX: Record<NodeKind, string> = { skill: 's_', playbook: 'p_', agent: 'a_' };
/** Control characters (C0, DEL, C1) and format characters (zero-width, bidirectional, tag characters…). */
const UNSAFE_CHARACTERS = /[\p{Cc}\p{Cf}]/gu;
const MARKDOWN_SPECIAL = /[\\`*_[\]<>|#&~]/g;
/** A `-` or `+` that would start a list item, and the `.` of a number that would start an ordered one. */
const LEADING_MARKER = /^[-+]/;
const LEADING_NUMBER = /^(\d+)\./;
/** The `:` that GitHub's autolinks need: after a scheme followed by `//`, or after `mailto` and `xmpp`. */
const SCHEME_COLON = /(?<=[A-Za-z][A-Za-z0-9+.-]*):(?=\/\/)|(?<=\b(?:mailto|xmpp)):/gi;
/** The `.` after `www`, which GitHub links without a scheme. */
const WWW_DOT = /(?<=www)\./gi;
/** GitHub renders `$…$` and `$$…$$` as math; HTML around the sign stops it and shows a plain `$`. */
const DOLLAR = /\$/g;
const DOLLAR_HTML = '<span>$</span>';
const LABEL_SAFE = /^[A-Za-z0-9 \-_.:/()]$/;
const ELLIPSIS = '…';
const NOTICE = 'Generated by `stackledger skills map` from the skill files; do not edit by hand, the next run replaces it.';
const DECLARED_NOTE = 'Only declared relations are drawn: `stackledger-skills` and `stackledger-agents` in a skill\'s `metadata`, and an agent\'s `skills`. '
  + 'A declaration says that a file asks for another; it does not prove that a tool loads it. Names mentioned in the text are never drawn.';
const SHAPES = 'Rounded box: playbook. Hexagon: agent. Plain box: skill.';
const ARROWS = 'An arrow goes from what brings an item in to what it brings in: loads (`stackledger-skills`), uses (`stackledger-agents`) or preloads (an agent\'s `skills`).';

/** The page file name of an item, without `.md`. */
export function pageFileName(name: string): string {
  if (name.length <= MAX_FILE_NAME && VALID_NAME.test(name) && !WINDOWS_DEVICE.test(name)) return name;
  const bytes = Buffer.from(name, 'utf8');
  const hexadecimal = `_${bytes.toString('hex')}`;
  if (hexadecimal.length <= MAX_FILE_NAME) return hexadecimal;
  const digest = createHash('sha256').update(bytes).digest('hex').slice(0, HASH_DIGITS);
  return `${hexadecimal.slice(0, HASHED_PREFIX)}-${digest}`;
}
/** The page of an item inside the map folder, `/`-separated. */
export function pagePath(node: Pick<MapNode, 'kind' | 'name'>): string {
  return `${KIND_FOLDERS[node.kind]}/${pageFileName(node.name)}.md`;
}
/** The stable Mermaid node ID of an item: kind prefix and page file name, `-` written as `_`. */
export function nodeId(node: Pick<MapNode, 'kind' | 'name'>): string {
  return ID_PREFIX[node.kind] + pageFileName(node.name).replaceAll('-', '_');
}

const withoutUnsafe = (text: string) => text.replace(UNSAFE_CHARACTERS, '');
/** `text` when it has at most `limit` code points, otherwise its first `keep` code points and `…`. */
const cut = (text: string, limit: number, keep: number) => {
  const points = Array.from(text);
  return points.length > limit ? points.slice(0, keep).join('') + ELLIPSIS : text;
};
/** One cleaned line escaped for Markdown. The special characters first, so the `\` the later steps
 * add are not escaped again, and `$` last, so the HTML around it is not escaped. */
function escapeMarkdown(line: string): string {
  return line.replace(MARKDOWN_SPECIAL, '\\$&')
    .replace(LEADING_MARKER, '\\$&')
    .replace(LEADING_NUMBER, '$1\\.')
    .replace(SCHEME_COLON, '\\:')
    .replace(WWW_DOT, '\\.')
    .replace(DOLLAR, () => DOLLAR_HTML);
}
/** Text for Markdown: one line, no control or format characters, special characters escaped. */
export function markdownText(text: string): string {
  return escapeMarkdown(withoutUnsafe(text.replace(/\s+/g, ' ')).trim());
}
/** A description for a page: one line, cleaned, cut to 1,023 code points and `…` when longer than 1,024, escaped. */
export function descriptionText(text: string): string {
  const line = withoutUnsafe(text.replace(/\s+/g, ' ')).trim();
  return escapeMarkdown(cut(line, MAX_DESCRIPTION_CODE_POINTS, MAX_DESCRIPTION_CODE_POINTS - 1));
}
/** A Mermaid label: cleaned, cut at 64 code points and `…`, everything outside the safe set as `#<code>;`. */
export function mermaidLabel(name: string): string {
  return Array.from(cut(withoutUnsafe(name), MAX_LABEL_CODE_POINTS, MAX_LABEL_CODE_POINTS), character => LABEL_SAFE.test(character) ? character : `#${character.codePointAt(0)};`).join('');
}

/** One node line, in its kind's shape. */
function nodeLine(id: string, node: MapNode): string {
  const label = `"${mermaidLabel(node.name)}"`;
  if (node.kind === 'playbook') return `  ${id}(${label})`;
  if (node.kind === 'agent') return `  ${id}{{${label}}}`;
  return `  ${id}[${label}]`;
}
/** A fenced `flowchart LR` block, or the fixed sentence when it is over the budget. */
function diagram(lines: string[], edges: number): string {
  const block = ['```mermaid', 'flowchart LR', ...lines, '```'].join('\n');
  if (edges > MAX_DIAGRAM_EDGES || block.length > MAX_DIAGRAM_CHARACTERS) {
    return `This set has ${edges} relations, too many for one diagram; the lists below hold them all.`;
  }
  return block;
}

/** The one-hop diagram of an item: what brings it in on the left (`in_`), what it brings in on the right (`out_`). */
function oneHop(graph: SkillGraph, node: MapNode): string {
  const center = nodeId(node);
  // graph.edges is sorted by source node, relation kind and target node, so these keep that order:
  // the left side's edges by source, then the item's own edges by kind and target.
  const edges = graph.edges.filter(edge => edge.to === node || edge.from === node);
  const leftEdges = edges.filter(edge => edge.to === node && edge.from !== node);
  const ownEdges = edges.filter(edge => edge.from === node);
  // Nodes by kind then name, the left side first; a neighbour on both sides appears on both, a
  // relation to itself is a loop on the item.
  const left = leftEdges.map(edge => edge.from), right = ownEdges.map(edge => edge.to).filter(other => other !== node);
  const lines = [...left.map(other => nodeLine(`in_${nodeId(other)}`, other)), nodeLine(center, node), ...right.map(other => nodeLine(`out_${nodeId(other)}`, other))];
  for (const edge of leftEdges) lines.push(`  in_${nodeId(edge.from)} -->|${edge.kind}| ${center}`);
  for (const edge of ownEdges) lines.push(`  ${center} -->|${edge.kind}| ${edge.to === node ? center : `out_${nodeId(edge.to)}`}`);
  lines.push('  classDef current stroke-width:4px', `  class ${center} current`);
  return diagram(lines, edges.length);
}

/** The index diagram: every drawn relation, with the nodes that take part in one. */
function indexDiagram(graph: SkillGraph): string {
  const used = new Set(graph.edges.flatMap(edge => [edge.from, edge.to]));
  const lines = graph.nodes.filter(node => used.has(node)).map(node => nodeLine(nodeId(node), node));
  for (const edge of graph.edges) lines.push(`  ${nodeId(edge.from)} -->|${edge.kind}| ${nodeId(edge.to)}`);
  return diagram(lines, graph.edges.length);
}

/** A Markdown link to another item's page, from a page `depth` folders below the map folder. */
function itemLink(node: MapNode, depth: number): string {
  return `[${markdownText(node.name)}](${'../'.repeat(depth)}${pagePath(node)})`;
}

/** Where the command runs and where the map goes, as real paths (links resolved). */
export interface MapPaths {
  /** The current folder. */
  current: string;
  /** The map folder. */
  out: string;
}
/** A path below `parent` with `/` separators, or undefined when it is not strictly inside (another
 * volume included, where relative() returns an absolute path). */
function inside(parent: string, child: string): string | undefined {
  const path = relative(parent, child);
  if (!path || path === '..' || path.startsWith(`..${sep}`) || isAbsolute(path)) return undefined;
  return path.split(sep).join('/');
}
/** Percent-encode one URL path segment, including the characters encodeURIComponent keeps that
 * Markdown link targets treat specially. */
const encodeSegment = (segment: string) => encodeURIComponent(segment).replace(/[!'()*]/g, character => `%${character.charCodeAt(0).toString(16).toUpperCase()}`);

/** A source file line: a relative link when both the file and the map are inside the current folder,
 * otherwise its path below its given folder and why it is not linked, never an absolute path. */
function sourceLine(file: SourceFile, kindFolder: string, paths: MapPaths): string {
  if (inside(paths.current, paths.out) === undefined && paths.out !== paths.current) {
    // A link from a map outside the current folder would spell out the folders above both.
    return `- ${markdownText(file.below)} (not linked: the map folder is outside the current folder)`;
  }
  const fromCurrent = inside(paths.current, file.real);
  if (fromCurrent === undefined) return `- ${markdownText(file.below)} (outside the current folder)`;
  const pageFolder = `${paths.out}${sep}${kindFolder}`;
  const target = relative(pageFolder, file.real);
  if (isAbsolute(target)) return `- ${markdownText(file.below)} (outside the current folder)`;
  const url = target.split(sep).map(segment => segment === '..' ? segment : encodeSegment(segment)).join('/');
  return `- [${markdownText(fromCurrent)}](${url})`;
}

const legend = (item: boolean) => `Legend: ${SHAPES}${item ? ' Thick border: this item.' : ''} ${ARROWS}`;
const relationList = (edges: MapEdge[], end: 'from' | 'to') => edges.length
  ? edges.map(edge => `- ${itemLink(edge[end], 1)} (${edge.kind})`).join('\n') : 'None.';

/** The page of one item. */
function itemPage(graph: SkillGraph, node: MapNode, paths: MapPaths): string {
  const description = descriptionText(node.description);
  const reached = reachedThrough(graph, node);
  const sections = [
    `# ${markdownText(node.name)}`,
    NOTICE,
    `Kind: ${node.kind}`,
    description || 'No description.',
    legend(true),
    oneHop(graph, node),
    `## Brought in by\n\n${relationList(incoming(graph, node), 'from')}`,
    `## Brings in\n\n${relationList(outgoing(graph, node), 'to')}`,
    `## Reached through\n\nItems that bring this one in through two or more relations.\n\n${reached.length ? reached.map(other => `- ${itemLink(other, 1)}`).join('\n') : 'None.'}`,
    `## Rules\n\n${node.rules.length ? node.rules.map(markdownText).join(', ') : 'None.'}`,
    `## Source files\n\n${node.files.map(file => sourceLine(file, KIND_FOLDERS[node.kind], paths)).join('\n')}`,
    `[Back to the index](../${INDEX_PAGE})`,
  ];
  return sections.join('\n\n') + '\n';
}

const HEADINGS: Record<NodeKind, string> = { playbook: 'Playbooks', agent: 'Agents', skill: 'Skills' };
const SINGULAR: Record<NodeKind, string> = { playbook: 'Playbook', agent: 'Agent', skill: 'Skill' };

/** One kind's table: each item with what it brings in and what brings it in. */
function kindTable(graph: SkillGraph, kind: NodeKind): string {
  const nodes = graph.nodes.filter(node => node.kind === kind).sort(compareListed);
  if (!nodes.length) return `## ${HEADINGS[kind]}\n\nNone.`;
  const cell = (edges: MapEdge[], end: 'from' | 'to') => edges.length ? edges.map(edge => `${itemLink(edge[end], 0)} (${edge.kind})`).join(', ') : 'none';
  const rows = nodes.map(node => `| ${itemLink(node, 0)} | ${cell(outgoing(graph, node), 'to')} | ${cell(incoming(graph, node), 'from')} |`);
  return [`## ${HEADINGS[kind]}`, '', `| ${SINGULAR[kind]} | Brings in | Brought in by |`, '|---|---|---|', ...rows].join('\n');
}

/** The index page. */
function indexPage(graph: SkillGraph, summary: SkillsSummary): string {
  const counts = [
    `- Skills: ${summary.skills}`, `- Playbooks: ${summary.playbooks}`, `- Agents: ${summary.agents}`, `- Rules: ${summary.rules}`,
    `- Ignored entries: ${summary.ignored}`, `- Errors: ${summary.errors}`, `- Warnings: ${summary.warnings}`,
  ].join('\n');
  const unclaimed = graph.nodes.filter(node => node.kind !== 'agent' && !graph.edges.some(edge => edge.to === node)).sort(compareListed);
  const sections = [
    '# Skills map',
    NOTICE,
    DECLARED_NOTE,
    `## Counts\n\n${counts}\n\nAn item with an error is not in the map. Run \`stackledger skills validate\` on the same folders to see every problem.`,
    `## Diagram\n\n${legend(false)}\n\n${graph.edges.length ? indexDiagram(graph) : 'No item declares a relation, so there is no diagram.'}`,
    kindTable(graph, 'playbook'),
    kindTable(graph, 'agent'),
    kindTable(graph, 'skill'),
    `## No declared incoming relations\n\nSkills and playbooks that nothing in the set brings in. A person may still load them by hand.\n\n${unclaimed.length ? unclaimed.map(node => `- ${itemLink(node, 0)}`).join('\n') : 'None.'}`,
  ];
  return sections.join('\n\n') + '\n';
}

/** Every page of the map: path inside the map folder (`/`-separated) and text, sorted by path. */
export function renderMap(graph: SkillGraph, summary: SkillsSummary, paths: MapPaths): Map<string, string> {
  const owners = new Map<string, MapNode>();
  for (const node of graph.nodes) {
    const path = pagePath(node), earlier = owners.get(path);
    if (earlier) {
      throw new InternalError(`stackledger skills map: ${earlier.files[0]!.path} and ${node.files[0]!.path} give the same page ${path}; `
        + 'rename one of them (nothing was written)');
    }
    owners.set(path, node);
  }
  const pages: [string, string][] = [[INDEX_PAGE, indexPage(graph, summary)]];
  for (const node of graph.nodes) pages.push([pagePath(node), itemPage(graph, node, paths)]);
  pages.sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0);
  return new Map(pages);
}
