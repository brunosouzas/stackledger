/** Build both sites of a catalogue into a staging folder: the internal building block of
 * `stackledger build` (design D1, D2, D8).
 *
 * What: prepareBuild(folder or loaded folder, staging, date) validates the catalogue, builds the staff site and then
 * the full site, each from its own SiteData, working copy and caches, and writes the root files:
 *   <staging>/site-staff/   <staging>/site-full/   <staging>/root/{_headers, robots.txt, .stackledger-build}
 * Each site also holds `_headers` and `robots.txt`. Nothing is written outside `staging`.
 *
 * The command (src/site/command.ts) checks the options and the output folder, creates `staging` as
 * `<out>/.stackledger-tmp-*`, publishes the five entries (src/site/publish.ts) and writes the report;
 * PreparedBuild carries the catalogue counts, the page counts and the full map's diagnostic lines.
 *
 * How Astro runs (proven by docs/spikes/2026-10-20-astro-build/): from a writable copy of the shipped
 * `site/` folder with the current directory set to it, `outDir` inside it, every dependency bundled
 * into the render step, packages resolved from this package through a Vite plugin, caches in staging
 * and telemetry off. process.chdir makes this one build at a time per process.
 *
 * What can go wrong: an Astro or Vite upgrade that emits a URL form relative.ts does not handle, or
 * inline code, fails the scan and throws before anything is published.
 */
import { chmodSync, cpSync, mkdirSync, readFileSync, readdirSync, realpathSync, renameSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadFolder, type Loaded } from '../source.js';
import { validateLoaded, type Catalogue } from '../validate.js';
import type { ViewName } from '../views.js';
import { siteColorNames } from '../schema.js';
import { mapNotes } from '../map/command.js';
import { buildSiteData, type SiteData } from './data.js';
import { ownerNames } from './owners.js';
import { HEADERS, MARKER, MARKER_NAME, POLICY, ROBOTS } from './policy.js';
import { listFiles, relativise, scan } from './relative.js';

const require = createRequire(import.meta.url);
const thisFile = fileURLToPath(import.meta.url);
const packageRoot = fileURLToPath(new URL('../../', import.meta.url));
const siteSource = join(packageRoot, 'site');

/** Font files copied from the @fontsource packages: Heebo for text, Signika for headings (as brunosouzas.com). */
const FONT_FILES: readonly [string, string][] = [
  ['@fontsource/heebo', 'heebo-latin-400-normal.woff2'],
  ['@fontsource/heebo', 'heebo-latin-600-normal.woff2'],
  ['@fontsource/signika', 'signika-latin-500-normal.woff2'],
  ['@fontsource/signika', 'signika-latin-700-normal.woff2'],
];

const HEX_COLOUR = /^#[0-9a-fA-F]{6}$/;

/** Every Astro preference a build reads, answered in the working copy (see prepareWorkingCopy). */
const ASTRO_PREFERENCES = { devToolbar: { enabled: false } };

export interface BuiltSite { dir: string; pages: number }
/** `notes` are the map's diagnostic lines for the full view, as `stackledger map` writes them. */
export interface PreparedBuild { catalogue: Catalogue; staff: BuiltSite; full: BuiltSite; root: string; notes: string[] }

export function packageVersion(): string {
  return (JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8')) as { version: string }).version;
}

/** The light-theme overrides from spec.site.colors; only #RRGGBB values reach the stylesheet. */
export function overrideCss(colors: SiteData['colors']): string {
  const lines = siteColorNames.flatMap(name => {
    const value = colors[name];
    if (value === undefined) return [];
    if (!HEX_COLOUR.test(value)) throw new Error('Site colours must be #RRGGBB');
    return [`  --color-${name}: ${value};`];
  });
  const header = '/* Generated by stackledger from spec.site.colors: light theme only. */\n';
  return lines.length ? `${header}:root {\n${lines.join('\n')}\n}\n` : header;
}

/** cpSync keeps the modes of a read-only install; Astro must write .astro/ and staging must be removable. */
function makeWritable(dir: string): void {
  chmodSync(dir, 0o755);
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) makeWritable(full);
    else if (entry.isFile()) chmodSync(full, 0o644);
  }
}

function prepareWorkingCopy(staging: string, view: ViewName, data: SiteData): string {
  const work = join(staging, `work-${view}`);
  cpSync(siteSource, work, { recursive: true });
  makeWritable(work);
  mkdirSync(join(work, 'src', 'data'), { recursive: true });
  writeFileSync(join(work, 'src', 'data', 'site.json'), JSON.stringify(data) + '\n');
  writeFileSync(join(work, 'src', 'data', 'policy.json'), JSON.stringify(POLICY) + '\n');
  writeFileSync(join(work, 'src', 'styles', 'override.css'), overrideCss(data.colors));
  // Astro reads its preferences from the project's .astro/settings.json before the user's home
  // folder; answering here keeps the build from touching $HOME (refused under the permission model).
  mkdirSync(join(work, '.astro'), { recursive: true });
  writeFileSync(join(work, '.astro', 'settings.json'), JSON.stringify(ASTRO_PREFERENCES) + '\n');
  mkdirSync(join(work, 'src', 'fonts'), { recursive: true });
  for (const [pkg, file] of FONT_FILES) cpSync(require.resolve(`${pkg}/files/${file}`), join(work, 'src', 'fonts', file));
  return work;
}

/** Resolve a bare import that fails from the working copy as if this module imported it (no node_modules link). */
function packageResolver() {
  return {
    name: 'stackledger:package-resolver',
    enforce: 'pre' as const,
    async resolveId(this: { resolve: (source: string, importer: string | undefined, options: object) => Promise<unknown> }, source: string, importer: string | undefined, options: object) {
      if (source.startsWith('.') || source.startsWith('/') || source.startsWith('\0') || source.includes(':')) return null;
      const own = await this.resolve(source, importer, { ...options, skipSelf: true });
      return own ?? this.resolve(source, thisFile, { ...options, skipSelf: true });
    },
  };
}

function astroConfig(staging: string, view: ViewName, work: string) {
  return {
    root: work,
    configFile: false as const,
    mode: 'production',
    logLevel: 'error' as const,
    output: 'static' as const,
    trailingSlash: 'always' as const,
    outDir: join(work, 'dist'),
    cacheDir: join(staging, `cache-${view}`, 'astro'),
    integrations: [],
    devToolbar: { enabled: false },
    prefetch: false,
    build: { format: 'directory' as const, inlineStylesheets: 'never' as const },
    vite: {
      cacheDir: join(staging, `cache-${view}`, 'vite'),
      build: { assetsInlineLimit: 0, modulePreload: false },
      // Bundle every dependency into the render step, so a package of the same name hoisted
      // elsewhere in the tree (cookie 0.7 from the MCP SDK) is never picked up instead of Astro's.
      ssr: { noExternal: true },
      environments: { prerender: { resolve: { noExternal: true } } },
      plugins: [packageResolver()],
    },
  };
}

async function buildView(staging: string, view: ViewName, data: SiteData): Promise<BuiltSite> {
  const work = prepareWorkingCopy(staging, view, data);
  // Telemetry must be off before Astro is first loaded.
  process.env.ASTRO_TELEMETRY_DISABLED = '1';
  const { build } = await import('astro');
  // Astro writes its prerender bundle inside outDir only when outDir is inside the current directory.
  const previous = process.cwd();
  process.chdir(work);
  try {
    await build(astroConfig(staging, view, work) as Parameters<typeof build>[0]);
  } finally {
    process.chdir(previous);
  }
  const dir = join(staging, `site-${view}`);
  renameSync(join(work, 'dist'), dir);
  relativise(dir);
  const problems = scan(dir);
  if (problems.length) throw new Error(`The ${view} site has URL forms or inline code the build does not allow: ${problems.join('; ')}`);
  writeFileSync(join(dir, '_headers'), HEADERS);
  writeFileSync(join(dir, 'robots.txt'), ROBOTS);
  return { dir, pages: listFiles(dir).filter(file => file.endsWith('.html')).length };
}

/** Build both sites and the root files into `staging`, which must exist and be empty. */
export async function prepareBuild(folder: string | Loaded, stagingPath: string, date: string, version = packageVersion()): Promise<PreparedBuild> {
  // Astro compares module paths with process.cwd(), which is always the real path (on macOS the
  // temporary folder /var is a link to /private/var), so the working copies use the real path too.
  const staging = realpathSync(stagingPath);
  const loaded = typeof folder === 'string' ? await loadFolder(folder) : folder;
  const catalogue = validateLoaded(loaded);
  // The staff site is built first, before the full data exists anywhere (site-security, One view per site).
  const owners = ownerNames(loaded.sources);
  const staff = await buildView(staging, 'staff', buildSiteData(catalogue, 'staff', version, undefined, owners).data);
  const fullData = buildSiteData(catalogue, 'full', version, date, owners);
  const full = await buildView(staging, 'full', fullData.data);
  const root = join(staging, 'root');
  mkdirSync(root);
  writeFileSync(join(root, '_headers'), HEADERS);
  writeFileSync(join(root, 'robots.txt'), ROBOTS);
  writeFileSync(join(root, MARKER_NAME), MARKER);
  return { catalogue, staff, full, root, notes: mapNotes(loaded, catalogue, fullData.geometry) };
}
