/** Public fictitious example acceptance and reproducible hero generation. Build first.
 * Uses actual folder/view data; collision checks are independent bounding-box intersections.
 */
import { test, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { validateFolder } from '../../src/validate.js';
import { applyView, resolveHidden } from '../../src/views.js';
import { buildMapModel } from '../../src/map/model.js';
import { layoutMap } from '../../src/map/layout.js';
import { root, run } from './helpers.js';
const example=join(root,'examples/northwind');
test('Labels do not collide in the example',async()=>{
 const catalogue=await validateFolder(example);expect(catalogue.summary).toMatchObject({errors:0,warnings:0});expect(catalogue.problems).toEqual([]);
 const g=layoutMap(buildMapModel(applyView(catalogue.served,'full',resolveHidden(catalogue)),'2027-06-01'));
 expect(g.stations).toHaveLength(17);expect(g.lines).toHaveLength(7);expect(g.unrouted).toEqual([]);expect(g.suggestions).toEqual([]);
 const hits=(a:any,b:any)=>a.x<b.x+b.w && b.x<a.x+a.w && a.y<b.y+b.h && b.y<a.y+a.h;
 for(const label of g.labels){
  for(const other of g.labels.filter(l=>l!==label))expect(hits(label.box,other.box),`${label.ref} covers ${other.ref}`).toBe(false);
  for(const station of g.stations)expect(hits(label.box,station.marker.box),`${label.ref} covers ${station.ref}`).toBe(false);
  for(const badge of g.badges)expect(hits(label.box,badge.box),`${label.ref} covers badge ${badge.text}`).toBe(false);
 }
});
test('Example YAML preserves demo titles, zone labels and Settings',async()=>{
 const c=await validateFolder(example);expect(c.served.settings).toHaveLength(1);expect(c.served.layouts[0]!.spec.zones).toEqual([{name:'finance',title:'Zone 2 · Finance',color:'#9B0056'}]);
 expect(c.served.components.find(s=>s.metadata.name==='google')!.metadata.title).toBe('Google Workspace');expect(c.served.licences.length).toBeGreaterThan(0);
});
test('SVG heroes are generated by stackledger map at the documented date',()=>{for(const theme of ['light','dark']){const r=run(['map',example,'--theme',theme,'--date','2027-06-01']);expect(r.status).toBe(0);expect(r.stderr).toBe('');expect(readFileSync(join(root,`docs/images/map-${theme}.svg`),'utf8')).toBe(r.stdout);}});
